from __future__ import annotations

from typing import Any

from app.models.enums import AgentRole


def build_agentic_plan(prompt: str, attached_source_ids: list[str] | None = None) -> dict[str, Any]:
    """Build the minimal agentic plan contract expected by the frontend and orchestration layer."""
    sources = attached_source_ids or []
    stages = [
        {
            "id": "source-study",
            "title": "Source study and schema validation",
            "summary": "Profile the attached source tables and verify the schema before transformation.",
            "agent_role": AgentRole.PROFILER.value,
            "status": "PENDING",
        },
        {
            "id": "warehouse-blueprint",
            "title": "Warehouse blueprint and ETL design",
            "summary": "Draft the warehouse structure, transformation logic, and expected outputs.",
            "agent_role": AgentRole.ENGINEER.value,
            "status": "PENDING",
        },
        {
            "id": "guardrail-review",
            "title": "Guardrail and compliance review",
            "summary": "Validate the design against read-only constraints, RGPD, and approvals.",
            "agent_role": AgentRole.GUARDIAN.value,
            "status": "PENDING",
        },
    ]
    return {
        "id": "plan_agentic_default",
        "title": "Agentic pipeline plan",
        "prompt": prompt,
        "summary": "Agentic pipeline blueprint generated by a supervisor that delegates concrete tasks to specialized agents.",
        "stages": stages,
        "reasoningPhases": [
            {
                "id": "phase-1",
                "title": "Source understanding",
                "detail": "Inspect the input sources and confirm what must be profiled.",
            },
            {
                "id": "phase-2",
                "title": "Warehouse design",
                "detail": "Translate the required transformations into a robust warehouse plan.",
            },
            {
                "id": "phase-3",
                "title": "Validation and guardrails",
                "detail": "Check compliance and approvals before execution is allowed.",
            },
        ],
        "kpis": [
            {"id": "net-recognized-revenue", "name": "Net recognized revenue"},
            {"id": "active-customer-360", "name": "Active customer 360"},
        ],
        "selectedKpiIds": [],
        "selectedAnswers": {},
        "status": "DRAFT",
        "compiledSql": "SELECT 1 AS readiness;",
        "attachedSourceIds": sources,
        "task_roles": [AgentRole.PROFILER.value, AgentRole.ENGINEER.value, AgentRole.GUARDIAN.value],
    }


def apply_plan_approval(
    plan: dict[str, Any],
    *,
    plan_id: str,
    selected_answers: dict[str, Any] | None = None,
    selected_kpi_ids: list[str] | None = None,
) -> dict[str, Any]:
    selected_answers = selected_answers or {}
    selected_kpi_ids = selected_kpi_ids or []
    output = {
        "status": "ACTIVE",
        "planId": plan_id,
        "selectedAnswers": selected_answers,
        "selectedKpiIds": selected_kpi_ids,
        "summary": "The agentic plan has been validated and the pipeline is ready for execution.",
        "stages": plan.get("stages", []),
        "prompt": plan.get("prompt", ""),
    }
    return output
